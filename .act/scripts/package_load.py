# One package of the lock, read and verified
# ---------------------------------------------------------------------------

@dataclass
class Package:
    id: str
    entry: dict
    folder: Path
    problems: list[str] = field(default_factory=list)   # empty: intact
    data: dict[str, bytes] = field(default_factory=dict)  # verified bytes of every file, by package-relative path

    @property
    def intact(self) -> bool:
        return not self.problems

    @property
    def version(self) -> str:
        value = self.entry.get("version")
        return value if isinstance(value, str) else ""

    def listed(self) -> list[str]:
        """The package-relative paths the lock lists, sorted."""
        files = self.entry.get("files")
        return sorted(rel for rel in files if isinstance(rel, str)) if isinstance(files, dict) else []

    def under(self, side: str, folder: str) -> list[str]:
        """The listed files directly inside <side>-template/<folder>/."""
        prefix = f"{side}-template/{folder}/"
        return [rel for rel in self.listed() if rel.startswith(prefix) and rel.count("/") == 2]

    def skills(self, side: str) -> dict[str, dict[str, str]]:
        """{skill name: {path inside the skill: package-relative path}} of one side."""
        found: dict[str, dict[str, str]] = {}
        prefix = f"{side}-template/skills/"
        for rel in self.listed():
            if rel.startswith(prefix) and rel.count("/") >= 3:
                name, _, rest = rel[len(prefix):].partition("/")
                found.setdefault(name, {})[rest] = rel
        return found

    def roles(self, side: str) -> dict[str, str]:
        return {Path(rel).stem: rel for rel in self.under(side, "agents") if rel.endswith(".md")}

    def imports(self, side: str) -> list[str]:
        """The project-relative paths of the rule files, coding sets and topics of one side, in that order."""
        out: list[str] = []
        for folder in ("rules", "coding", "topics"):
            out += [f"{PACKAGES_DIR}/{self.id}/{rel}" for rel in self.under(side, folder) if rel.endswith(".md")]
        return out

    def path(self, rel: str) -> Path:
        return self.folder / rel

    def text(self, rel: str) -> str:
        return self.data[rel].decode("utf-8", errors="replace")


def _plain(base: Path, rel: str) -> Optional[str]:
    """None when `rel` below `base` is a plain file reached through plain folders, else why not."""
    parts = rel.split("/")
    if rel.startswith("/") or any(part in ("", ".", "..") for part in parts) or "\\" in rel or ":" in parts[0]:
        return f"`{rel}` is not a path inside the package"
    current = base
    for index, part in enumerate(parts):
        current = current / part
        try:
            info = os.lstat(current)
        except OSError:
            return f"`{rel}` is missing"
        if actlib.is_redirect(info):
            return f"`{rel}` is reached through a link or junction"
        last = index == len(parts) - 1
        if last != _is_file(info):
            return f"`{rel}` is not a plain file"
    return None


def _is_file(info: os.stat_result) -> bool:
    return stat.S_ISREG(info.st_mode)


def read_package(root: Path, package_id: str, entry: dict, folder: Optional[Path] = None) -> Package:
    """The package `package_id` of the lock with its folder checked against the lock entry: every listed file
    present as a plain file with the recorded hash. `problems` names what fails (all of it, the first ten). `folder`
    reads the package from there instead of `.act-local/packages/<id>/` (a package not yet installed)."""
    folder = folder if folder is not None else root / ".act-local" / "packages" / package_id
    package = Package(package_id, entry, folder)
    problems = package.problems
    files = entry.get("files")
    if not _ID_RE.match(package_id):
        problems.append(f"`{package_id}` is not a package id")
        return package
    if not isinstance(files, dict) or "package.md" not in files:
        problems.append("the lock entry lists no files (no `package.md`): it cannot be checked")
        return package
    try:
        info = os.lstat(folder)
    except OSError:
        problems.append(f"its folder .act-local/packages/{package_id}/ is missing")
        return package
    if actlib.is_redirect(info) or not _is_dir(info):
        problems.append(f"its folder .act-local/packages/{package_id}/ is a link or not a folder")
        return package
    for rel, recorded in sorted(files.items()):
        if not isinstance(rel, str) or not isinstance(recorded, str):
            problems.append("the lock entry has a file entry that is not path and hash")
            continue
        why = _plain(folder, rel)
        if why:
            problems.append(why)
            continue
        try:
            data = (folder / rel).read_bytes()
        except OSError as error:
            problems.append(f"`{rel}` cannot be read ({error.__class__.__name__})")
            continue
        if actlib.lock_hash(data) != recorded:
            problems.append(f"`{rel}` differs from the lock")
        else:
            package.data[rel] = data
    if len(problems) > 10:
        del problems[10:]
        problems.append("and more")
    return package


def _is_dir(info: os.stat_result) -> bool:
    return stat.S_ISDIR(info.st_mode)


