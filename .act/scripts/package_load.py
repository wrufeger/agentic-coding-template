def load_writes(root: Path, packages: dict[str, dict], *, folders: Optional[dict[str, Path]] = None
                ) -> dict[str, Optional[bytes]]:
    """Every project file whose content loading changes for exactly this `packages` mapping (the lock's
    `packages` as it would be): project-relative posix path -> the new content, None when the file goes. Empty when
    nothing changes. Never `.act-lock.json`, `docs/ai/config.md` or anything under `.act-local/`. Reads only; with
    `{}` it gives what restores the state without packages (import lines the scope cut come back through
    rules.sync_core_cut(), which sync_packages() runs). `folders` names, per package id, the folder to read that
    package from instead of `.act-local/packages/<id>/` (a package that is staged, not yet installed)."""
    return plan_for(root, packages, folders=folders).writes


def copy_content(root: Path, packages: dict[str, dict], *, folders: Optional[dict[str, Path]] = None
                 ) -> dict[str, Optional[bytes]]:
    """The full target content of every copy path the intact packages of this `packages` mapping give or take: project
    path -> bytes the copy holds when loading is done, None for a file the packages give no copy (a template file a
    replacing skill leaves out). Computed from the lock's record and the hash-checked package folders alone, never
    from the files as they are now; reads only. A path the packages do not touch is not in it. Empty when there is
    no lock or nothing is intact. Used by protected_watch to tell the copies loading wrote from other changes.
    `folders` is as for load_writes()."""
    if actlib.read_lock_at(root) is None:
        return {}
    intact = [p for p in (read_package(root, pid, entry, (folders or {}).get(pid)) for pid, entry in packages.items())
              if p.intact]
    if not any(p.skills(side) or p.roles(side) for p in intact for side in SIDES):
        return {}
    env = _env(root)
    wants = _wants(root, env, intact)
    found: dict[str, Optional[bytes]] = {dest: want.data for dest, want in wants.items()}
    if env.claude:
        found.update(_extension_targets(root, env, intact, wants))
    return found


def _prune(root: Path, rel: str) -> None:
    """Remove the empty folders a deleted copy leaves, up to the target folder (never above)."""
    stops = {".claude/skills", ".agents/skills", _CLAUDE_AGENTS}
    parent = (root / rel).parent
    while parent != root:
        relative = parent.relative_to(root).as_posix()
        if relative in stops:
            return
        try:
            parent.rmdir()
        except OSError:
            return
        parent = parent.parent


def _write_record(root: Path, record: dict[str, dict], restored: dict[str, dict]) -> None:
    """The lock after loading: `package_copies` = `record` (the key goes when it is empty, so a project without
    packages has none), an empty `packages` left by the last package's removal goes too, and the template copies put
    back (`restored`) carry the template's hash under `copies`. Every other key stays as it is; nothing is written
    when nothing changes."""
    path = root / ".act-lock.json"
    data = actlib._read_json(path)
    if data is None:
        return
    wanted = dict(data)
    if record:
        wanted[COPIES_KEY] = dict(sorted(record.items()))
    else:
        wanted.pop(COPIES_KEY, None)
    if wanted.get(actlib.PACKAGES_LOCK_KEY) == {}:
        del wanted[actlib.PACKAGES_LOCK_KEY]
    if restored and isinstance(wanted.get("copies"), dict):
        wanted["copies"] = {**wanted["copies"], **restored}
    if wanted != data:
        actlib.write_text_lf(path, json.dumps(wanted, indent=2, ensure_ascii=False) + "\n")


def sync_packages(root: Path, write: bool = True, *, strict: bool = False) -> list[str]:
    """Apply load_writes(root, <the lock's packages>) and bring the import lines of docs/ai/rules.md in line with
    the scope (rules.sync_core_cut). Returns the project paths it changed, or with `write=False` would change.
    A project without a readable `.act-lock.json` is left alone. Copies are recorded under the lock's
    `package_copies`. Not intact packages are skipped and named by plan_for(); never deletes or overwrites a
    copy a person edited. A second call changes nothing. A file that cannot be written or deleted is skipped, the
    session start goes on; with `strict=True` the OS error is raised instead, so `packages.py add` and `remove` can
    put everything back."""
    if not (root / ".act-lock.json").is_file() or actlib.read_lock_at(root) is None:
        return []
    plan = plan_for(root, actlib.read_packages(root))
    changed = sorted(plan.writes)
    rules_path = root / RULES_MD
    if write:
        was_generated = False
        if RULES_MD in plan.writes:
            try:
                if Path(actlib.repo_root()).resolve() == root.resolve():
                    was_generated = actlib.generated_unchanged(rules_path, actlib.read_cache()["generated"].get(RULES_MD, ""))
            except (OSError, RuntimeError):
                was_generated = False
        done: set[str] = set()
        for rel, data in sorted(plan.writes.items()):
            path = root / rel
            if unit_copies.dest_is_linked(root, rel):
                continue
            try:
                if data is None:
                    path.unlink()
                    _prune(root, rel)
                else:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(data)
            except OSError:
                if strict:
                    raise
                continue
            done.add(rel)
        if RULES_MD in plan.writes and was_generated:
            try:
                generated = dict(actlib.read_cache()["generated"])
                generated[RULES_MD] = actlib.generated_hash(rules_path)
                actlib.write_cache({"generated": generated})
            except OSError:
                pass
        _write_record(root, plan.record, {rel: entry for rel, entry in plan.restored.items() if rel in done})
    if rules_path.is_file():
        before = rules_path.read_bytes() if write else b""
        core = rules.sync_core_cut(root, write=write)
        moved = core.switched_off + core.restored
        if moved and RULES_MD not in changed and (not write or rules_path.read_bytes() != before):
            changed.append(RULES_MD)
            changed.sort()
    return changed
