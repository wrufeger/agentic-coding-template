@dataclass
class _Want:
    """What a copy should hold: `data` (None: the copy goes), the package that wants it, `base` ("template": a copy
    the template writes too; "new": only the package does) and `kind` ("skill" or "role")."""
    data: Optional[bytes]
    package: str
    base: str
    kind: str


@dataclass
class Plan:
    writes: dict[str, Optional[bytes]] = field(default_factory=dict)   # project path -> content, None: goes
    record: dict[str, dict] = field(default_factory=dict)               # the lock's `package_copies` afterwards
    messages: list[str] = field(default_factory=list)                   # copies left alone, with the reason
    problems: dict[str, list[str]] = field(default_factory=dict)        # package id -> why it is not loaded
    copies: set[str] = field(default_factory=set)                       # the writes that are copies (not rules.md)
    restored: dict[str, dict] = field(default_factory=dict)             # template copies put back -> their `copies` entry


def copy_path_ok(path: object) -> bool:
    """Whether `path` (a key of the lock's `package_copies`, or a path about to be written) is a place a package copy
    may be: project-relative with `/`, below one of COPY_ROOTS with at least one more part, no `.` or `..` part, no
    drive, no absolute path, no backslash, no control character."""
    if not isinstance(path, str) or not path.startswith(COPY_ROOTS):
        return False
    if "\\" in path or ":" in path or any(ord(ch) < 32 for ch in path):
        return False
    parts = path.split("/")
    return not any(part in ("", ".", "..") for part in parts) and len(parts) > 2


def _body(data: bytes) -> bytes:
    match = _FRONT_RE.match(data)
    return data[match.end():] if match else data


def _same(a: bytes, b: bytes) -> bool:
    return actlib.fold_crlf(a) == actlib.fold_crlf(b)


def _appendix(data: bytes, skill_md: bool) -> bytes:
    """The text of a package file appended to the template's: a SKILL.md without its frontmatter."""
    return (_body(data) if skill_md else data).strip(b"\r\n") + b"\n"


def _roots(init, tools: list[str]) -> list[str]:
    return [dest for dest, gate in init.SKILL_TARGET_DIRS if init._skill_target_active(gate, tools)]


def _skill_wants(
    root: Path, packages: list[Package], template_targets: dict[str, Path], roots: list[str],
    render_template: Callable[[str, Path], bytes], render_package: Callable[[str, Path], bytes],
) -> dict[str, _Want]:
    """The skill copies the intact `packages` want, by destination. `template_targets` is what the template's own
    writer would write (destination -> source), `render_*` give the bytes of a copy from a source file."""
    template_names = set(act_profile.template_skills(root).values())
    cut = act_profile.read_cut(root).skills
    replaced: dict[str, tuple[Package, dict[str, str]]] = {}
    extended: dict[str, list[tuple[Package, dict[str, str]]]] = {}
    brought: dict[str, tuple[Package, dict[str, str]]] = {}
    for package in packages:
        for side in SIDES:
            for name, files in package.skills(side).items():
                if name in template_names:
                    if name in cut:
                        continue
                    if side == "pre":
                        replaced.setdefault(name, (package, files))
                    else:
                        extended.setdefault(name, []).append((package, files))
                else:
                    brought.setdefault(name, (package, files))
    wants: dict[str, _Want] = {}
    for dest_root in roots:
        def dest_of(name: str, rel: str) -> str:
            return f"{dest_root}/{name}/{rel}"

        for name, (package, files) in replaced.items():
            have = {d[len(dest_of(name, "")):]: d for d in template_targets if d.startswith(dest_of(name, ""))}
            for rel, pkg_rel in files.items():
                dest = dest_of(name, rel)
                wants[dest] = _Want(render_package(dest, package.path(pkg_rel)), package.id,
                                    "template" if rel in have else "new", "skill")
            for rel, dest in have.items():
                if rel not in files:
                    wants[dest] = _Want(None, package.id, "template", "skill")
        for name, extenders in extended.items():
            have = {d[len(dest_of(name, "")):]: d for d in template_targets if d.startswith(dest_of(name, ""))}
            appended: dict[str, list[bytes]] = {}
            owner: dict[str, Package] = {}
            for package, files in extenders:
                for rel, pkg_rel in files.items():
                    dest = dest_of(name, rel)
                    data = package.data[pkg_rel]
                    if rel not in have:
                        wants.setdefault(dest, _Want(render_package(dest, package.path(pkg_rel)), package.id, "new", "skill"))
                        continue
                    try:
                        data.decode("utf-8")
                    except UnicodeDecodeError:
                        wants[dest] = _Want(render_package(dest, package.path(pkg_rel)), package.id, "template", "skill")
                        continue
                    appended.setdefault(rel, []).append(_appendix(data, rel == "SKILL.md"))
                    owner.setdefault(rel, package)
            for rel, chunks in appended.items():
                dest = have[rel]
                base = render_template(dest, template_targets[dest])
                if not base.endswith(b"\n"):
                    base += b"\n"
                wants[dest] = _Want(base + b"\n" + b"\n".join(chunks), owner[rel].id, "template", "skill")
        for name, (package, files) in brought.items():
            for rel, pkg_rel in files.items():
                dest = dest_of(name, rel)
                wants[dest] = _Want(render_package(dest, package.path(pkg_rel)), package.id, "new", "skill")
    return wants


def skill_overrides(
    root: Path, template_targets: dict[str, Path], render: Callable[[str, Path], bytes],
) -> dict[str, Optional[bytes]]:
    """For the template's own copy writers (update.py): of the destinations in `template_targets` (destination ->
    source, what the writer would write), those the active, intact packages change: the bytes the copy holds
    instead (a replaced or extended skill), or None for a file the package that replaces the skill leaves out.
    `render(dest, source)` gives the writer's bytes for a source. Empty without packages. Never raises: a
    package that cannot be read changes nothing."""
    try:
        packages = actlib.read_packages(root)
        if not packages:
            return {}
        intact = [p for p in (read_package(root, pid, entry) for pid, entry in packages.items()) if p.intact]
        if not any(p.skills(side) for p in intact for side in SIDES):
            return {}
        init = _init()
        tools = unit_copies.copy_tools()
        wants = _skill_wants(root, intact, template_targets, _roots(init, tools), render,
                             lambda dest, src: render(dest, src))
        return {dest: want.data for dest, want in wants.items() if dest in template_targets}
    except Exception:  # noqa: BLE001 - the writer then writes what the template says, as without packages
        return {}


def _init():
    import init  # deferred: heavy, and only a project that has package units needs it
    return init


def _bridge_bytes(root: Path, init, role: str, source: Path, tiers_data: dict, overrides: dict,
                  variant: bool = False) -> Optional[bytes]:
    """The bytes init.py's writer gives the Claude Code bridge of `role` made from `source` (with `variant`: its
    "-high" variant file), or None, with the `model`/`effort` lines the session-start refresh derives for it. The
    writer leaves an `effort` line out when the source has no `reasoning` line, which the bumped variant of such a
    role needs, so the first session start would rewrite the file: the refresh's own step is applied here too."""
    with actlib.scratch_dir("role-bridge", root) as folder:  # the project's scratch place, like update.py's bridge check
        dest = folder / ".claude" / "agents" / (f"{role}-high.md" if variant else f"{role}.md")
        init.write_agent_bridge_file(role, source, dest, False, root, tiers_data, overrides, variant)
        if not dest.is_file():
            return None
        data = dest.read_bytes()
    try:
        fields = tiers.split_frontmatter(source.read_text(encoding="utf-8"))[0]
        written = data.decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return data
    if "tier" not in fields:  # a fixed model: the refresh leaves such a file as it is
        return data
    model, effort, _problem, _tier, _reasoning = tiers.effective_model_effort(
        root, role, fields.get("tier", ""), fields.get("reasoning", ""), tiers_data, overrides, bump_variant=variant)
    if model is None:
        return data
    refreshed = tiers.apply_resolved_fields(written, model, effort)  # None: nothing to change
    return data if refreshed is None else refreshed.encode("utf-8")


def _variant_applies(init, fields: dict, role: str, tiers_data: dict, overrides: dict) -> bool:
    """Whether a role file with these frontmatter `fields` gets a "-high" variant by the conditions
    init.agent_bridge_variant_targets() applies besides the declaration: a `tier`, not the expert tier (unless the
    project sets a model), not a reasoning already at the top of the tool's scale (the project's own override of
    either counts)."""
    if "tier" not in fields:
        return False
    override = overrides.get(role, {})
    if "model" not in override and override.get("tier", fields.get("tier", "")) == "expert":
        return False
    scale = (tiers.tool_table(tiers_data, "claude-code") or {}).get("reasoning_scale") or []
    return not (scale and override.get("reasoning", fields.get("reasoning", "")) == scale[-1])


def _template_declares_variant(root: Path, init, role: str) -> bool:
    """Whether the template's bridge of `role` declares a "-high" variant (`high-variant: true`)."""
    try:
        text = (root / ".act" / "bridges" / "agents" / f"{role}.md").read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return init.bridge_declares_high_variant(tiers.split_frontmatter(text)[0])


def _role_block(package: Package, data: bytes) -> bytes:
    """The text a post-template role file of `package` adds to a role copy, between its marks."""
    marker = package.id.encode()
    return b"\n<!-- act:package " + marker + b" -->\n" + _appendix(data, False) + b"<!-- /act:package " + marker + b" -->\n"


def _post_role(package: Package, role: str) -> Optional[str]:
    """The package-relative path of the post-template role file named `role` (any case), or None."""
    for name, rel in package.roles("post").items():
        if name.lower() == role.lower():
            return rel
    return None


def _extenders(packages: list[Package], template_roles: dict[str, str], cut_roles: frozenset[str]) -> dict[str, list[Package]]:
    """{template role: the intact packages whose post-template role file extends it}, cut roles left out."""
    extend: dict[str, list[Package]] = {}
    for package in packages:
        for name in package.roles("post"):
            real = template_roles.get(name.lower())
            if real and real not in cut_roles:
                extend.setdefault(real, []).append(package)
    return extend


def _decide_copy(
    root: Path, dest: str, want: _Want, current: Optional[bytes], record: Optional[dict], removed: set[str],
    copies: dict, template_bytes: Callable[[str], Optional[bytes]], plan: Plan,
) -> None:
    """Fill `plan` for one destination a package wants (see the module header for the rules)."""
    digest = (lambda data: actlib.lock_hash(_body(data) if want.kind == "role" else data))
    entry = {"package": want.package, "base": want.base, "kind": want.kind}
    path = root / dest
    if want.data is None:  # a template file a replacing package leaves out
        if current is None:
            plan.record[dest] = {**entry, "sha256": "", "dropped": True}
            return
        original = template_bytes(dest)
        lock_hash = copies.get(dest, {}).get("sha256") if isinstance(copies.get(dest), dict) else None
        if (record and actlib.lock_hash(current) == record.get("sha256")) or (original is not None and _same(current, original)) \
                or actlib.matches_lock_hash(current, lock_hash):
            plan.writes[dest] = None
            plan.record[dest] = {**entry, "sha256": "", "dropped": True}
        else:
            plan.messages.append(f"{dest}: edited, kept although package {want.package} leaves it out")
        return
    wanted = digest(want.data)
    if current is None:
        if want.base == "new" and dest not in removed:
            plan.writes[dest] = want.data
            plan.record[dest] = {**entry, "sha256": wanted}
        return  # a template copy that is not there (cut, removed, not made yet): the template's writer decides
    if (_same(_body(current), _body(want.data)) if want.kind == "role" else _same(current, want.data)):
        plan.record[dest] = {**entry, "sha256": wanted}
        return
    mine = bool(record) and digest(current) == record.get("sha256") and not record.get("dropped")
    original = template_bytes(dest) if want.base == "template" and not mine else None
    lock_hash = copies.get(dest, {}).get("sha256") if isinstance(copies.get(dest), dict) else None
    untouched = original is not None and (
        _same(_body(current), _body(original)) if want.kind == "role" else
        (_same(current, original) or actlib.matches_lock_hash(current, lock_hash)))
    if mine or untouched:
        plan.writes[dest] = want.data
        plan.record[dest] = {**entry, "sha256": wanted}
    else:
        plan.messages.append(f"{dest}: differs from package {want.package}'s copy and was not written by it, kept")


def _restore_copy(
    root: Path, dest: str, record: dict, current: Optional[bytes], removed: set[str],
    template_bytes: Callable[[str], Optional[bytes]], plan: Plan,
) -> None:
    """A recorded copy no package wants any more: back to the template's, or gone, if nobody edited it."""
    if record.get("dropped"):
        original = template_bytes(dest) if current is None and dest not in removed else None
        if original is not None:
            plan.writes[dest] = original  # the template file the replaced skill had lost
        return
    if current is None:
        return
    digest = actlib.lock_hash(_body(current) if record.get("kind") == "role" else current)
    if digest != record.get("sha256"):
        plan.messages.append(f"{dest}: edited, kept although package {record.get('package')} no longer wants it")
        return
    original = template_bytes(dest) if record.get("base") == "template" else None
    plan.writes[dest] = original  # None: a new unit's copy goes


def _role_appendices(root: Path, packages: list[Package], active: set[str], frozen: set[str], plan: Plan,
                     template_roles: dict[str, str], cut_roles: frozenset[str]) -> None:
    """Role copies of post-template roles: the package's text after the body, between marks. Also cuts out the
    blocks of every package no longer in the lock (a frozen, broken package's block stays)."""
    agents = root / _CLAUDE_AGENTS
    if not agents.is_dir():
        return
    extend = _extenders(packages, template_roles, cut_roles)
    for path in sorted(agents.glob("*.md")):
        try:
            current = path.read_bytes()
        except OSError:
            continue
        role = path.stem
        if role.endswith("-high") and role[: -len("-high")] in extend:  # the variant file of an extended role
            if tiers.split_frontmatter(current.decode("utf-8", errors="replace"))[0].get("variant-of") == role[: -len("-high")]:
                role = role[: -len("-high")]
        wanted = extend.get(role, [])
        if b"<!-- act:package " not in current and not wanted:
            continue
        dest = f"{_CLAUDE_AGENTS}/{path.name}"
        if unit_copies.dest_is_linked(root, dest):
            continue
        text = _ROLE_BLOCK_RE.sub(lambda m: m.group(0) if m.group("id").decode() in frozen else b"", current)
        for package in wanted:
            rel = _post_role(package, role)
            if rel is None or "\r\n" in current.decode("utf-8", errors="replace"):
                continue  # a CRLF file: left alone, a person owns it
            text += _role_block(package, package.data[rel])
        if text != current:
            plan.writes[dest] = text
            plan.copies.add(dest)


def plan_for(root: Path, packages: dict[str, dict], *, folders: Optional[dict[str, Path]] = None) -> Plan:
    """The plan for exactly this `packages` mapping, as it would be in the lock. Reads only. `folders` names, per
    package id, the folder to read that package from instead of `.act-local/packages/<id>/` (a staged package)."""
    plan = Plan()
    lock = actlib.read_lock_at(root)
    if lock is None:
        return plan
    pkgs = {pid: read_package(root, pid, entry, (folders or {}).get(pid)) for pid, entry in packages.items()}
    plan.problems = {pid: package.problems for pid, package in pkgs.items() if package.problems}
    intact = [p for p in pkgs.values() if p.intact]
    _plan_rules(root, pkgs, plan)
    recorded_raw = lock.get(COPIES_KEY)
    recorded: dict[str, dict] = {}
    ignored: dict[str, dict] = {}  # keys that are no copy place: never written or deleted, left in the lock as they are
    if isinstance(recorded_raw, dict):
        for key, value in recorded_raw.items():
            if not isinstance(key, str) or not isinstance(value, dict):
                continue
            if copy_path_ok(key):
                recorded[key] = value
            else:
                ignored[key] = value
                plan.messages.append(
                    f".act-lock.json: {json.dumps(key)[:300]} in `{COPIES_KEY}` is no place for a copy (only below .claude/skills/, "
                    ".agents/skills/ and .claude/agents/); ignored, nothing is written or deleted there")
    plan.record = {**ignored, **recorded}
    has_units = any(p.skills(side) or p.roles(side) for p in intact for side in SIDES)
    stale_roles = _has_role_marks(root)
    if has_units or recorded or stale_roles:
        _plan_copies(root, pkgs, intact, lock, recorded, plan)
    plan.writes = {rel: data for rel, data in plan.writes.items() if rel == RULES_MD or copy_path_ok(rel)}
    return plan


def _has_role_marks(root: Path) -> bool:
    agents = root / _CLAUDE_AGENTS
    try:
        return agents.is_dir() and any(b"<!-- act:package " in p.read_bytes() for p in agents.glob("*.md"))
    except OSError:
        return False


def marked_owners(text: str) -> dict[str, str]:
    """{rule id: package id} for every rule line of docs/ai/rules.md `text` that carries a package mark."""
    found: dict[str, str] = {}
    for line in text.split("\n"):
        mark = act_profile.PACKAGE_MARK_RE.search(line.rstrip("\r"))
        row = act_profile._RULE_ROW_RE.match(line[:mark.start()]) if mark else None
        if row:
            found[row.group("id")] = mark.group("id")
    return found


def _rules_text(current: str, pkgs: dict[str, Package], marks_text: Optional[str] = None) -> str:
    """`current` with the blocks and marks of `pkgs`. A mark of a package that cannot be read (its folder is
    missing or differs from the lock) is taken over from `marks_text` (default: `current`), so it stays."""
    pre = [rules.PackageImports(p.id, p.version, p.imports("pre")) for p in pkgs.values()]
    post = [rules.PackageImports(p.id, p.version, p.imports("post")) for p in pkgs.values()]
    disabled: dict[str, str] = {}
    for package in pkgs.values():
        if package.intact:
            for rule_id in act_profile.manifest_disables(package.text("package.md")):
                disabled.setdefault(rule_id, package.id)
    for rule_id, owner in marked_owners(current if marks_text is None else marks_text).items():
        if owner in pkgs and not pkgs[owner].intact:
            disabled.setdefault(rule_id, owner)
    return rules.apply_package_marks(rules.apply_package_blocks(current, pre, post), disabled, set(pkgs))


def rules_text(root: Path, text: str, packages: dict[str, dict]) -> str:
    """`text` of docs/ai/rules.md (or the template's bridge text for it) as it is with `packages` (the lock's record):
    the import blocks and the marks of disabled rules. For the bridge refresh, so a re-derived file keeps them."""
    try:
        marks_text = (root / RULES_MD).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        marks_text = ""
    return _rules_text(text, {pid: read_package(root, pid, entry) for pid, entry in packages.items()}, marks_text)


def _plan_rules(root: Path, pkgs: dict[str, Package], plan: Plan) -> None:
    try:
        current = (root / RULES_MD).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return
    for number, mark in rules.stray_package_marks(current):
        plan.messages.append(
            f"{RULES_MD}: line {number}: `{mark}` is part of no block (the mark of its pair is missing); nothing around "
            "it was removed, the blocks are written anew -- delete the stray mark, and the lines it left, to clear this note")
    text = _rules_text(current, pkgs)
    if text != current:
        plan.writes[RULES_MD] = text.encode("utf-8")


@dataclass
class _Env:
    """What the copy planning and copy_content() both read: the template's writers' targets, the tier data, the cut."""
    init: object
    tools: list[str]
    tiers_data: dict
    overrides: dict
    template_targets: dict[str, Path]     # destination -> source, what init.py's skill copy writer writes
    template_variants: dict[str, Path]    # destination -> bridge, the "-high" variant files the template makes
    template_roles: dict[str, str]
    cut: object
    claude: bool                          # whether Claude Code's role files are kept at all


def _env(root: Path) -> _Env:
    init = _init()
    tools = unit_copies.copy_tools()
    claude = any(actlib.normalize_tool(t) == "claude-code" for t in tools)
    variants = dict(init.agent_bridge_variant_targets(root, tools)) if claude else {}
    bridges = root / ".act" / "bridges" / "agents"
    return _Env(init, tools, init.tiers.load_tiers(root), init.tiers.read_role_overrides(root),
                init.copy_targets(root, tools), {d: s for d, s in variants.items() if s.parent == bridges},
                act_profile.template_roles(root), act_profile.read_cut(root), claude)


def _wants(root: Path, env: _Env, intact: list[Package]) -> dict[str, _Want]:
    """Every copy the intact packages want: skills, and roles for Claude Code, with their variant files."""
    def render(dest: str, src: Path) -> bytes:
        return env.init.skill_copy_bytes(root, dest, src, env.tiers_data, env.overrides)

    wants = _skill_wants(root, intact, env.template_targets, _roots(env.init, env.tools), render, render)
    if env.claude:
        _role_wants(root, env, intact, wants)
    return wants


def _plan_copies(root: Path, pkgs: dict[str, Package], intact: list[Package], lock: dict,
                 recorded: dict[str, dict], plan: Plan) -> None:
    env = _env(root)
    init, tiers_data, overrides, template_targets = env.init, env.tiers_data, env.overrides, env.template_targets
    removed = {item for item in lock.get("removed_by_user", []) if isinstance(item, str)}
    copies = lock.get("copies") if isinstance(lock.get("copies"), dict) else {}
    frozen = {pid for pid, package in pkgs.items() if package.problems}
    wants = _wants(root, env, intact)
    if env.claude:
        _role_appendices(root, intact, set(pkgs), frozen, plan, env.template_roles, env.cut.roles)

    def template_bytes(dest: str) -> Optional[bytes]:
        if dest.startswith(_CLAUDE_AGENTS + "/"):
            name = Path(dest).stem
            if dest in env.template_variants:  # a "-high" variant file the template makes
                return _bridge_bytes(root, init, name[: -len("-high")], env.template_variants[dest], tiers_data,
                                     overrides, True)
            bridge = root / ".act" / "bridges" / "agents" / f"{name}.md"
            return _bridge_bytes(root, init, name, bridge, tiers_data, overrides) if bridge.is_file() else None
        src = template_targets.get(dest)
        return init.skill_copy_bytes(root, dest, src, tiers_data, overrides) if src is not None else None

    for dest, want in sorted(wants.items()):
        if unit_copies.dest_is_linked(root, dest):
            plan.messages.append(f"{dest}: a link or junction is in the way, not written")
            continue
        path = root / dest
        try:
            current = path.read_bytes() if path.is_file() else None
        except OSError:
            continue
        _decide_copy(root, dest, want, current, recorded.get(dest), removed, copies, template_bytes, plan)
        if dest in plan.writes:
            plan.copies.add(dest)
    for dest, entry in sorted(recorded.items()):
        if dest in wants or entry.get("package") in frozen:
            continue
        if unit_copies.dest_is_linked(root, dest):
            continue
        path = root / dest
        try:
            current = path.read_bytes() if path.is_file() else None
        except OSError:
            continue
        _restore_copy(root, dest, entry, current, removed, template_bytes, plan)
        plan.record.pop(dest, None)
        if dest in plan.writes:
            plan.copies.add(dest)
        restored_data = plan.writes.get(dest)
        if restored_data is not None and dest in template_targets:
            # the template's own copy is back: update.py must find its hash under `copies`, not the package's bytes it
            # recorded while the package was active (else the copy counts as edited by hand and is never refreshed)
            old = copies.get(dest)
            source = old.get("source") if isinstance(old, dict) and isinstance(old.get("source"), str) else None
            if source is None:
                try:
                    source = template_targets[dest].relative_to(root).as_posix()
                except ValueError:
                    source = template_targets[dest].as_posix()
            plan.restored[dest] = {"source": source, "sha256": actlib.lock_hash(restored_data)}


def _role_wants(root: Path, env: _Env, intact: list[Package], wants: dict[str, _Want]) -> None:
    """The bridges of new roles and of replacing (pre-template) roles, as wants, each with its "-high" variant file
    where one is due: for a replacing role when the template declares one for the role and the package file has a
    tier a variant makes sense for (else the template's variant file goes, it would no longer match the base), for
    a new role on the conditions an own role of the project gets one by (no declaration needed)."""
    init, tiers_data, overrides = env.init, env.tiers_data, env.overrides
    for package in intact:
        for side in SIDES:
            for name, rel in package.roles(side).items():
                real = env.template_roles.get(name.lower())
                if real and (real in env.cut.roles or side == "post"):
                    continue  # cut, or an extension: handled by _role_appendices
                data = _bridge_bytes(root, init, name, package.path(rel), tiers_data, overrides)
                if data is None:
                    continue
                base = "template" if real else "new"
                wants[f"{_CLAUDE_AGENTS}/{name}.md"] = _Want(data, package.id, base, "role")
                high = f"{_CLAUDE_AGENTS}/{name}-high.md"
                fields = tiers.split_frontmatter(package.text(rel))[0]
                variant = None
                if (not real or _template_declares_variant(root, init, real)) \
                        and _variant_applies(init, fields, name, tiers_data, overrides):
                    variant = _bridge_bytes(root, init, name, package.path(rel), tiers_data, overrides, True)
                if variant is not None:
                    wants[high] = _Want(variant, package.id, base, "role")
                elif real and high in env.template_variants:
                    wants[high] = _Want(None, package.id, "template", "role")


def _extension_targets(root: Path, env: _Env, intact: list[Package], wants: dict[str, _Want]) -> dict[str, bytes]:
    """The full content of an extended role's copy (and of its variant file): what the role would hold without the
    extension (the template's bridge, or the replacing package's), plus the marked block of each extending package."""
    found: dict[str, bytes] = {}
    for real, extenders in _extenders(intact, env.template_roles, env.cut.roles).items():
        bridge = root / ".act" / "bridges" / "agents" / f"{real}.md"
        for variant in (False, True):
            dest = f"{_CLAUDE_AGENTS}/{real}{'-high' if variant else ''}.md"
            have = wants.get(dest)
            if have is not None:
                data = have.data
            elif (not variant or dest in env.template_variants) and bridge.is_file():
                data = _bridge_bytes(root, env.init, real, bridge, env.tiers_data, env.overrides, variant)
            else:
                data = None
            if data is None:
                continue
            for package in extenders:
                rel = _post_role(package, real)
                if rel is not None:
                    data += _role_block(package, package.data[rel])
            found[dest] = data
    return found


