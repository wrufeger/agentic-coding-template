#!/usr/bin/env python3
# -*- coding: utf-8 -*-
#
# Purpose: Loading of the active packages (the lock's `packages` record, folders under .act-local/packages/): what
#          a package brings takes effect in the project, and goes again without it. A library, no command line;
#          packages.py `add`/`remove` and the session start call sync_packages(), doctor.py and protected_watch
#          read the same plan. Format of a package: `.act/formats/package.md`.
# What it does, all of it derived from the lock and the package folders, nothing from memory:
#   docs/ai/rules.md   two marked blocks of "@" lines (rules.apply_package_blocks) -- the package's rule files,
#                      coding sets and topics, pre before the template's rule imports, post before the overrides --
#                      and the rules a package `disables` unchecked with a mark (rules.apply_package_marks). A rule
#                      file all of whose rules are off this way loses its "@" through act_profile.read_cut(), like
#                      `exclude`; sync_packages() ends with rules.sync_core_cut() so the import lines follow at once.
#   skill copies       <side>/skills/<name>/ -> .claude/skills/ and .agents/skills/ (the targets of own skills): a new
#                      unit gets its copy, a pre-template unit with a template skill's name replaces that skill's
#                      copy (template files the package lacks go), a post-template one appends its SKILL.md text
#                      to the template's and adds its further files.
#   role copies        <side>/agents/<name>.md -> .claude/agents/<name>.md: new role = a bridge from the package
#                      file (like an own role's), pre-template = that bridge instead of the template's, post-template
#                      = its text after the body between `<!-- act:package <id> -->` marks.
#                      A role's "-high" variant file follows its base role: a replacing role gives it too (made from the
#                      package file the way init.py makes a variant, when the template declares one for the role and the
#                      package file has a tier a variant makes sense for), an extending role's text is appended to it as
#                      well; a new role gets one on the rules an own role of the project gets one by.
#   Without the package the template copies come back byte for byte (skills: regenerated by init.py's own
#   writer; roles: the template bridge regenerated, the marked block cut out) and a new unit's copy goes.
# Rules:   Nothing loads from a package that is not intact: an entry whose folder is missing, is a link, or holds
#          a file that differs from the lock is *broken*. What derives from the lock alone stays (import lines,
#          marks), what needs the folder (copies) is left as it is, nothing is deleted or rebuilt, and the
#          problem is named (Plan.problems; doctor.py gives the fix). A copy a person edited is never
#          overwritten or deleted. Copies are recorded under the lock's `package_copies` -- never under `copies`
#          (update.py would take them for the template's or own units); update.py asks skill_overrides() for the
#          source of a template skill's copy so it never writes the template version over a replaced or extended
#          unit. load_writes() writes nothing; sync_packages() is the one writer. No note of what it wrote is kept:
#          protected_watch asks copy_content() what the active packages give a copy path, independent of the file.
# Limits:  Roles are handled for Claude Code (.claude/agents/), not for Copilot's .github/agents/; a pre-template
#          coding set with a template set's name cannot cut the template's set (nothing existing does that) and is
#          imported next to it.

